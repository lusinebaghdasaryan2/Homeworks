"""script1.py

Main execution script for Innovation Diffusion Analysis (Apple AirPods Pro 3).
Loads data/dataset1.csv, estimates parameters, forecasts adoption, and outputs
plots.
"""

import os
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from helper_functions import (
    bass_cumulative,
    fermi_market_potential,
    fit_bass_model,
    forecast_diffusion,
)

# Ensure output directories exist
os.makedirs("img", exist_ok=True)
os.makedirs("data", exist_ok=True)

# ---------------------------------------------------------
# 1. LOAD & AGGREGATE HISTORICAL DATA
# ---------------------------------------------------------
raw_df = pd.read_csv("data/dataset1.csv")

# Extract iPod sales from launch (Q4/01 onwards)
ipod_raw = raw_df[["Time", "iPod"]].dropna().copy()
ipod_raw.rename(columns={"iPod": "quarterly_sales"}, inplace=True)

# Parse 4-digit fiscal year from 'Time' (e.g., 'Q4/01' -> '2001')
ipod_raw["Year"] = "20" + ipod_raw["Time"].str.split("/").str[1]

# Aggregate into annual sums
annual_df = ipod_raw.groupby("Year")["quarterly_sales"].sum().reset_index()

# Filter for complete 13-year lifecycle (2002 to 2014)
annual_df = annual_df[
    (annual_df["Year"] >= "2002") & (annual_df["Year"] <= "2014")
].reset_index(drop=True)

annual_df["t"] = annual_df.index + 1
annual_df["cum_sales"] = annual_df["quarterly_sales"].cumsum()

years = annual_df["t"].values
cum_sales = annual_df["cum_sales"].values

print("=" * 60)
print("HISTORICAL IPOD DATA (from data/dataset1.csv):")
print(
    annual_df[["Year", "t", "quarterly_sales", "cum_sales"]].rename(
        columns={"quarterly_sales": "annual_sales (M)"}
    )
)
print("=" * 60)

# ---------------------------------------------------------
# 2. ESTIMATE BASS PARAMETERS
# ---------------------------------------------------------
p, q, M_ipod = fit_bass_model(years, cum_sales)

print(f"Estimated Coefficient of Innovation (p) : {p:.5f}")
print(f"Estimated Coefficient of Imitation (q)  : {q:.5f}")
print(f"Estimated Market Potential (M_ipod)     : {M_ipod:.2f} million units")
print("=" * 60)

# ---------------------------------------------------------
# 3. FERMI ESTIMATION & DIFFUSION FORECAST
# ---------------------------------------------------------
# Installed base 1.4B * 40% earbud users * 25% Pro tier capture = 140M
M_airpods = fermi_market_potential(
    installed_base_m=1400, earbud_pct=0.40, pro_tier_pct=0.25
)
forecast_df = forecast_diffusion(p, q, M_target=M_airpods, periods=10)

print(f"AirPods Pro 3 Global Target Market (M): {M_airpods:.1f}M units\n")
print("PROJECTED AIRPODS PRO 3 ADOPTION:")
print(forecast_df.to_string(index=False))
print("=" * 60)

# ---------------------------------------------------------
# 4. PLOTS & EXPORT TO img/
# ---------------------------------------------------------
# Plot 1: Historical Fit
t_dense = np.linspace(1, len(years), 100)
plt.figure(figsize=(9, 5))
plt.scatter(
    years,
    cum_sales,
    color="crimson",
    s=50,
    label="Actual iPod Sales (Apple SEC 10-K)",
)
plt.plot(
    t_dense,
    bass_cumulative(t_dense, p, q, M_ipod),
    color="navy",
    linewidth=2,
    label=f"Bass Model Fit (p={p:.3f}, q={q:.3f})",
)
plt.title(
    "Historical Diffusion of Look-Alike Innovation (Apple iPod 2002–2014)",
    fontsize=13,
)
plt.xlabel("Years Since Launch (t)", fontsize=11)
plt.ylabel("Cumulative Sales (Millions)", fontsize=11)
plt.legend()
plt.grid(True, linestyle="--", alpha=0.6)
plt.tight_layout()
plt.savefig("img/image1.png", dpi=300)
plt.close()

# Plot 2: Forecast
fig, ax1 = plt.subplots(figsize=(9, 5))
ax1.set_xlabel("Years After Launch (t)", fontsize=11)
ax1.set_ylabel("Annual Adopters (Millions)", color="tab:blue", fontsize=11)
ax1.bar(
    forecast_df["Year (t)"],
    forecast_df["Annual Adopters (M)"],
    color="tab:blue",
    alpha=0.7,
    width=0.5,
    label="Annual Sales S(t)",
)
ax1.tick_params(axis="y", labelcolor="tab:blue")

ax2 = ax1.twinx()
ax2.set_ylabel("Cumulative Adopters (Millions)", color="tab:red", fontsize=11)
ax2.plot(
    forecast_df["Year (t)"],
    forecast_df["Cumulative Adopters (M)"],
    color="tab:red",
    marker="o",
    linewidth=2,
    label="Cumulative Adopters N(t)",
)
ax2.tick_params(axis="y", labelcolor="tab:red")

plt.title(
    f"Bass Model Diffusion Forecast for Apple AirPods Pro 3 (M = {M_airpods}M)",
    fontsize=13,
)
fig.tight_layout()
plt.savefig("img/image2.png", dpi=300)
plt.close()

print("Success: Generated and saved img/image1.png and img/image2.png.")